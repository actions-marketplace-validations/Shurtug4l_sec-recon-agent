#!/usr/bin/env python3
"""Regenerate `src/sec_recon_agent/redteam/atlas.py` from a MITRE ATLAS release.

The red-team battery, the scorecard and docs/mitre_atlas.md name ATLAS
techniques by ID. Names written from memory drift: an ID reused for the wrong
technique reads as authoritative and nothing fails. This script pins the
official vocabulary in code so a test can check every tag and every
"AML.Txxxx (Name)" mention against it.

Usage:
    curl -sSfLo /tmp/ATLAS.yaml \\
        https://raw.githubusercontent.com/mitre-atlas/atlas-data/main/dist/ATLAS.yaml
    uv run python scripts/gen_atlas_vocab.py /tmp/ATLAS.yaml

Sub-techniques are named "<parent>: <sub-technique>", as atlas.mitre.org
displays them.
"""

import argparse
import hashlib
import json
from pathlib import Path

import yaml

OUTPUT = Path("src/sec_recon_agent/redteam/atlas.py")
SOURCE_URL = "https://raw.githubusercontent.com/mitre-atlas/atlas-data/main/dist/ATLAS.yaml"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("atlas_yaml", type=Path)
    args = parser.parse_args()

    raw = args.atlas_yaml.read_bytes()
    data = yaml.safe_load(raw)
    matrix = data["matrices"][0]
    techniques = {t["id"]: t for t in matrix["techniques"]}
    names: dict[str, str] = {}
    for tid, t in sorted(techniques.items()):
        parent = t.get("specializes") or t.get("subtechnique-of")
        names[tid] = f"{techniques[parent]['name']}: {t['name']}" if parent else t["name"]
    tactics = {t["id"]: t["name"] for t in matrix["tactics"]}

    lines = [
        '"""MITRE ATLAS vocabulary, generated by scripts/gen_atlas_vocab.py. Do not edit.',
        "",
        f"Source: {SOURCE_URL}",
        f"ATLAS version: {data['version']}",
        f"Source SHA-256: {hashlib.sha256(raw).hexdigest()}",
        '"""',
        "",
        f'ATLAS_VERSION = "{data["version"]}"',
        "",
        "ATLAS_TACTICS: dict[str, str] = {",
        *(f'    "{k}": {json.dumps(v, ensure_ascii=False)},' for k, v in tactics.items()),
        "}",
        "",
        "ATLAS_TECHNIQUES: dict[str, str] = {",
        *(f'    "{k}": {json.dumps(v, ensure_ascii=False)},' for k, v in names.items()),
        "}",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUTPUT}: {len(tactics)} tactics, {len(names)} techniques, ATLAS {data['version']}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
